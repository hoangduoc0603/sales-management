function resolveColumnType(name: string): TableDefinitionDTO['headers'][number]['type'] {
  if (name.endsWith('Json')) return 'json';
  if (name.endsWith('At') || name === 'effectiveFrom' || name === 'effectiveTo') return 'timestamp';
  if (
    name === 'schemaVersion' ||
    name === 'recordVersion' ||
    name === 'draftVersion' ||
    name === 'lineSetVersion' ||
    name === 'tenderSetVersion' ||
    name === 'rowSetVersion' ||
    name === 'backupSetVersion' ||
    name === 'runtimeSetVersion' ||
    name === 'rowIndex' ||
    name === 'renderVersion' ||
    name === 'quantity' ||
    name === 'attempt' ||
    name === 'capacityPct' ||
    name === 'factor' ||
    name === 'priority' ||
    name === 'usageLimit' ||
    name === 'usedCount' ||
    name === 'rowCount' ||
    name === 'validCount' ||
    name === 'invalidCount' ||
    name === 'errorCount' ||
    name.endsWith('Vnd') ||
    name.endsWith('Milli') ||
    name.endsWith('Days') ||
    name.endsWith('Bytes')
  ) {
    return 'integer';
  }
  if (
    name.startsWith('is') ||
    name.startsWith('has') ||
    name.startsWith('requires') ||
    name.endsWith('Enabled') ||
    name.endsWith('Tracking') ||
    name === 'readOnly' ||
    name === 'evidence' ||
    name === 'setIsEmpty' ||
    name === 'writeFrozen' ||
    name === 'saleEnabled' ||
    name === 'purchaseEnabled' ||
    name === 'directSaleEnabled'
  ) {
    return 'boolean';
  }
  return 'string';
}

function findDefinition(
  repository: TableRegistryRepository,
  tableName: string,
): TableDefinitionDTO {
  const definition = repository.listDefinitions().find((candidate) => candidate.tableName === tableName);

  if (definition === undefined) {
    throw new Error(`Unknown table: ${tableName}`);
  }

  return definition;
}
